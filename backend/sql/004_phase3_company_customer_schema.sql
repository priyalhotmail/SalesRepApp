CREATE TABLE IF NOT EXISTS customer_change_requests (
  id INT NOT NULL AUTO_INCREMENT,
  customer_id INT NOT NULL,
  requested_by_id INT NOT NULL,
  reviewed_by_id INT NULL,
  status ENUM('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED') NOT NULL DEFAULT 'PENDING',
  requested_changes JSON NOT NULL,
  reason VARCHAR(500) NULL,
  review_note VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  reviewed_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  KEY customer_change_requests_customer_id_idx (customer_id),
  KEY customer_change_requests_requested_by_id_idx (requested_by_id),
  KEY customer_change_requests_reviewed_by_id_idx (reviewed_by_id),
  KEY customer_change_requests_status_idx (status),
  CONSTRAINT customer_change_requests_customer_id_fkey FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT customer_change_requests_requested_by_id_fkey FOREIGN KEY (requested_by_id) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT customer_change_requests_reviewed_by_id_fkey FOREIGN KEY (reviewed_by_id) REFERENCES users(id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

